 */
function safe_fopen(string $file, string $flags){
	$dir = dirname($file);
	if(!@mkdir($dir, recursive: true) && !is_dir($dir)){
		throw new \RuntimeException("Couldn't create directory: $dir");
	}
	$result = fopen($file, $flags);
	if($result === false){
		throw new \RuntimeException("Failed to open file: $file");
	}
	return $result;
}

function generateItemTypeIds(int $startId, array $ids, string $type, string $path) : void{
	$namespace = "pocketmine\\" . strtolower($type);

	$file = safe_fopen(dirname(__DIR__, 2) . $path, 'wb');

	$fileHeader = Filesystem::fileGetContents(__DIR__ . "/templates/header.php");
	fwrite($file, $fileHeader);
	fwrite($file, <<<"HEADER"

namespace $namespace;

/**
 * Every item in {@link Vanilla{$type}s} has a corresponding constant in this class. These constants can be used to
 * identify and compare item types efficiently using {@link $type::getTypeId()}.
 *
 * WARNING: These are NOT a replacement for Minecraft legacy IDs. Do **NOT** hardcode their values, or store them in
 * configs or databases. They will change without warning.
 *
 * This class is generated automatically from the item type dictionary for the current version. Do not edit it manually.
 */
final class {$type}TypeIds{

    private function __construct(){
       //NOOP
    }


HEADER
	);

	$itemId = $startId;
	foreach(Utils::stringifyKeys($ids) as $id){
		fwrite($file, "\tpublic const " . $id . " = " . $itemId . ";\n");
		$itemId++;
	}

	fwrite($file, "
    public const FIRST_UNUSED_ITEM_ID = $itemId;
    
    private static int \$nextDynamicId = self::FIRST_UNUSED_ITEM_ID;
    
    /**
     * Returns a new runtime item type ID, e.g. for use by a custom item.
     */
    public static function newId() : int{
       return self::\$nextDynamicId++;
    }
    
    public static function fromBlockTypeId(int \$blockTypeId) : int{
       if(\$blockTypeId < 0){
          throw new \InvalidArgumentException(\"Block type IDs cannot be negative\");
       }
       //negative item type IDs are treated as block IDs
       return -\$blockTypeId;
    }
    
    public static function toBlockTypeId(int \$itemTypeId) : ?int{
       if(\$itemTypeId > 0){ //not a blockitem
          return null;
       }
       return -\$itemTypeId;
    }\n");

	fwrite($file, "}\n");
	fclose($file);
}

function getValues(string $clazz, array $ordreStrict = []) : array{
	$ids = [];

	$ref = new \ReflectionClass($clazz);
	foreach($ref->getMethods(\ReflectionMethod::IS_PUBLIC) as $method){
		if ($method->isConstructor() || $method->getName() === 'setup') {
			continue;
		}

		$returnType = $method->getReturnType();
		if ($returnType === null) {
			continue;
		}

		$return = $returnType->getName();
		if (!str_contains($return, "\\")) {
			continue;
		}

		$ids[] = $method->getName();
	}

	// Si on a fourni un ordre strict, on trie le tableau selon cet ordre
	if (!empty($ordreStrict)) {
		usort($ids, function($a, $b) use ($ordreStrict) {
			$posA = array_search($a, $ordreStrict, true);
			$posB = array_search($b, $ordreStrict, true);

			if ($posA !== false && $posB !== false) return $posA <=> $posB;
			if ($posA !== false) return -1;
			if ($posB !== false) return 1;

			return strcmp($a, $b);
		});
	}

	return $ids;
}

